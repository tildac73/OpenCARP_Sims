#!/usr/bin/env python3
"""Collect every verification result under a folder into one readable file.

    python3 verification/summarise.py runs/verification            # writes runs/verification/verification_numbers.md

For each check: the Methodology statement it supports, how the number was obtained, the code revision
and software that produced it, and the values (lists of records as tables). Failed checks are listed
with their error; nothing is omitted or filled in.
"""
import csv
import json
import sys
from pathlib import Path


def fmt(value):
    if isinstance(value, bool) or value is None:
        return str(value)
    if isinstance(value, float):
        if value != value:
            return "NaN"
        return f"{value:.4g}" if abs(value) < 1e5 else f"{value:.6g}"
    if isinstance(value, (list, tuple)) and all(not isinstance(v, (dict, list)) for v in value):
        return "[" + ", ".join(fmt(v) for v in value) + "]"
    if isinstance(value, dict) and all(not isinstance(v, (dict, list)) for v in value.values()):
        return ", ".join(f"{k} {fmt(v)}" for k, v in value.items())
    return json.dumps(value)


def table(records):
    columns = []
    for record in records:
        columns += [k for k in record if k not in columns]
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(fmt(record.get(c, "")) for c in columns) + " |" for record in records]
    return lines


def render(values, level=0):
    lines = []
    for key, value in values.items():
        if isinstance(value, list) and value and all(isinstance(v, dict) for v in value):
            flat = [{k: v for k, v in record.items() if not (isinstance(v, list) and v and isinstance(v[0], dict))} for record in value]
            lines += ["", f"**{key}**", ""] + table(flat)
            for record in value:                                             # nested per-row tables (e.g. per-beat tables)
                for k, v in record.items():
                    if isinstance(v, list) and v and isinstance(v[0], dict):
                        label = ", ".join(f"{a} {fmt(b)}" for a, b in record.items() if not isinstance(b, (list, dict)))[:80]
                        lines += ["", f"*{key} / {k} ({label})*", ""] + table(v)
        elif isinstance(value, dict) and any(isinstance(v, (dict, list)) for v in value.values()):
            lines += ["", f"**{key}**"] + render(value, level + 1)
        else:
            lines.append(f"- {key}: {fmt(value)}")
    return lines


def main():
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "runs/verification")
    lines = ["# Verification numbers for the Methodology", "",
             "Generated by verification/summarise.py from the JSON and CSV results below this folder. "
             "Kinds: derivation (arithmetic on configured values), numerical (computed by the analysis code), "
             "simulation (openCARP run), estimator (statistical recovery test).", ""]
    for path in sorted(root.rglob("*.json")):
        if "work" in path.relative_to(root).parts:
            continue
        result = json.loads(path.read_text())
        if "status" not in result:
            continue
        provenance = result.get("provenance", {})
        lines += [f"## {path.relative_to(root).with_suffix('')}", "",
                  f"- status: {result['status']}; kind: {result.get('kind', '-')}",
                  f"- revision: {provenance.get('gitRevision', '?')}; written {provenance.get('writtenAt', '?')}; "
                  f"versions: {fmt(provenance.get('versions', {}))}"]
        if result["status"] != "completed":
            lines += [f"- **error:** {result.get('error')}", ""]
            continue
        lines += [f"- supports: {result.get('supports')}", f"- method: {result.get('method')}"]
        lines += render(result.get("values", {})) + [""]
    for path in sorted(root.rglob("changepoint_recovery_summary.csv")):
        with open(path) as stream:
            rows = list(csv.DictReader(stream))
        lines += [f"## {path.relative_to(root).with_suffix('')}", "",
                  "- kind: estimator; Wang's mcp call on synthetic profiles (verification/changepoint_recovery.R)", ""]
        lines += table([{k: (float(v) if v.replace('.', '', 1).replace('-', '', 1).replace('e', '', 1).isdigit() else v) for k, v in row.items()} for row in rows]) + [""]
    target = root / "verification_numbers.md"
    target.write_text("\n".join(lines) + "\n")
    print(target)


if __name__ == "__main__":
    main()
